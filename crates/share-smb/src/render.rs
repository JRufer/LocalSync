use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use sync_core::config::{AppConfig, resolve_under_local_root};
use thiserror::Error;
use uuid::Uuid;

#[derive(Debug, Error)]
pub enum RenderError {
    #[error("failed to resolve share path for '{name}': {reason}")]
    PathResolution { name: String, reason: String },
    #[error("I/O error writing Samba share config {path}: {source}")]
    Io {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
}

/// Renders the contents of `/etc/samba/shares-syncd.conf` deterministically from `AppConfig`.
pub fn render_shares_conf(config: &AppConfig) -> Result<String, RenderError> {
    let mut out = String::new();
    out.push_str("# Auto-generated by LocalSync (drive-syncd / drivectl).\n");
    out.push_str("# Do not edit by hand; changes will be overwritten atomically.\n\n");

    let mut sorted_shares = config.shares.clone();
    sorted_shares.sort_by(|a, b| a.share_name.cmp(&b.share_name));

    for share in &sorted_shares {
        let abs_path =
            resolve_under_local_root(&config.local_root, &share.rel_path).map_err(|reason| {
                RenderError::PathResolution {
                    name: share.share_name.clone(),
                    reason,
                }
            })?;

        let comment = share
            .comment
            .clone()
            .unwrap_or_else(|| format!("LocalSync Google Drive folder {}", share.rel_path));
        // Sanitize newlines out of comment
        let clean_comment = comment.replace(['\r', '\n'], " ");

        out.push_str(&format!("[{}]\n", share.share_name));
        out.push_str(&format!("   comment = {clean_comment}\n"));
        out.push_str(&format!("   path = {}\n", abs_path.display()));
        out.push_str("   browseable = yes\n");
        out.push_str(&format!(
            "   read only = {}\n",
            if share.read_only { "yes" } else { "no" }
        ));
        out.push_str("   guest ok = no\n");
        out.push_str(&format!("   create mask = {}\n", config.samba.create_mask));
        out.push_str(&format!(
            "   directory mask = {}\n",
            config.samba.directory_mask
        ));

        if let Some(ref user) = config.samba.force_user {
            if !user.trim().is_empty() {
                out.push_str(&format!("   force user = {}\n", user.trim()));
            }
        }
        if let Some(ref group) = config.samba.force_group {
            if !group.trim().is_empty() {
                out.push_str(&format!("   force group = {}\n", group.trim()));
            }
        }

        if config.samba.macos_fruit {
            out.push_str("   vfs objects = fruit streams_xattr\n");
            out.push_str("   fruit:metadata = stream\n");
            out.push_str("   fruit:posix_rename = yes\n");
        }
        out.push('\n');
    }

    Ok(out)
}

/// Atomically writes `/etc/samba/shares-syncd.conf` (or the configured `shares_conf_path`)
/// via a temporary sibling file, `sync_all()`, and `rename()`.
pub fn write_shares_conf_atomic(config: &AppConfig) -> Result<PathBuf, RenderError> {
    let target = &config.samba.shares_conf_path;
    let rendered = render_shares_conf(config)?;

    let parent = target.parent().unwrap_or_else(|| Path::new("."));
    if !parent.as_os_str().is_empty() && !parent.exists() {
        fs::create_dir_all(parent).map_err(|source| RenderError::Io {
            path: parent.to_path_buf(),
            source,
        })?;
    }

    let tmp_path = parent.join(format!(
        ".tmp.{}.{}",
        Uuid::new_v4(),
        target
            .file_name()
            .and_then(|s| s.to_str())
            .unwrap_or("shares-syncd.conf")
    ));

    {
        let mut f = fs::File::create(&tmp_path).map_err(|source| RenderError::Io {
            path: tmp_path.clone(),
            source,
        })?;
        f.write_all(rendered.as_bytes())
            .and_then(|_| f.sync_all())
            .map_err(|source| RenderError::Io {
                path: tmp_path.clone(),
                source,
            })?;
    }

    fs::rename(&tmp_path, target).map_err(|source| RenderError::Io {
        path: target.clone(),
        source,
    })?;

    Ok(target.clone())
}

#[cfg(test)]
mod tests {
    use super::*;
    use sync_core::config::AppConfig;
    use tempfile::tempdir;

    #[test]
    fn renders_and_atomically_writes_samba_shares_conf() {
        let dir = tempdir().unwrap();
        let local_root = dir.path().join("drive-images");
        std::fs::create_dir_all(local_root.join("Today")).unwrap();
        let conf_path = dir.path().join("shares-syncd.conf");
        let db_path = dir.path().join("state.db");

        let toml_str = format!(
            r#"
            root_folder_id = "root_1"
            local_root = "{}"
            db_path = "{}"
            tailscale_ip = "100.64.0.10"

            [samba]
            shares_conf_path = "{}"
            force_user = "drivesync"
            force_group = "drivesync"

            [[shares]]
            share_name = "today"
            rel_path = "Today"
            read_only = false
            comment = "Today Photos"
            "#,
            local_root.display(),
            db_path.display(),
            conf_path.display()
        );

        let cfg = AppConfig::parse_and_validate(&toml_str).unwrap();
        write_shares_conf_atomic(&cfg).unwrap();

        let content = std::fs::read_to_string(&conf_path).unwrap();
        assert!(content.contains("[today]"));
        assert!(content.contains("read only = no"));
        assert!(content.contains("create mask = 0664"));
        assert!(content.contains("directory mask = 0775"));
        assert!(content.contains("vfs objects = fruit streams_xattr"));
    }
}
